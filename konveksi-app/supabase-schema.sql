-- 1. Tabel Produk
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_produk VARCHAR(50) UNIQUE NOT NULL,
    nama_produk VARCHAR(150) NOT NULL,
    kategori VARCHAR(50) NOT NULL CHECK (kategori IN ('Seragam Sekolah', 'Baju Olahraga', 'Wearpack Praktik')),
    deskripsi TEXT DEFAULT '',
    harga NUMERIC(12, 0) NOT NULL DEFAULT 0,
    stok INT NOT NULL DEFAULT 0,
    status_aktif SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Tabel Pesanan
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_pesanan VARCHAR(50) UNIQUE NOT NULL,
    nama_pemesan VARCHAR(100) NOT NULL,
    nis_kelas VARCHAR(50) NOT NULL,
    no_hp VARCHAR(25) NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    ukuran VARCHAR(10) NOT NULL CHECK (ukuran IN ('S', 'M', 'L', 'XL', 'XXL')),
    jumlah INT NOT NULL DEFAULT 1,
    total_harga NUMERIC(12, 0) NOT NULL DEFAULT 0,
    catatan TEXT DEFAULT '',
    status_pesanan VARCHAR(50) NOT NULL DEFAULT 'Menunggu Konfirmasi'
        CHECK (status_pesanan IN ('Menunggu Konfirmasi', 'Diproses / Dijahit', 'Siap Diambil', 'Selesai', 'Dibatalkan')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Tabel Admin
CREATE TABLE IF NOT EXISTS public.admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nama_lengkap VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;

-- 5. Kebijakan RLS (Policies)
-- Products: Publik dapat membaca produk yang aktif, Admin dapat mengelola semua
DROP POLICY IF EXISTS "Public can view active products" ON public.products;
CREATE POLICY "Public can view active products"
    ON public.products FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Allow all for authenticated/anon product management" ON public.products;
CREATE POLICY "Allow all for authenticated/anon product management"
    ON public.products FOR ALL
    USING (true)
    WITH CHECK (true);

-- Orders: Publik dapat membuat pesanan dan mencari status pesanan
DROP POLICY IF EXISTS "Public can view orders" ON public.orders;
CREATE POLICY "Public can view orders"
    ON public.orders FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Public can insert orders" ON public.orders;
CREATE POLICY "Public can insert orders"
    ON public.orders FOR INSERT
    WITH CHECK (true);

DROP POLICY IF EXISTS "Admin can update orders" ON public.orders;
CREATE POLICY "Admin can update orders"
    ON public.orders FOR UPDATE
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "Admin can delete orders" ON public.orders;
CREATE POLICY "Admin can delete orders"
    ON public.orders FOR DELETE
    USING (true);

-- Admins: Akses untuk verifikasi login admin
DROP POLICY IF EXISTS "Admins select policy" ON public.admins;
CREATE POLICY "Admins select policy"
    ON public.admins FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Admins update policy" ON public.admins;
CREATE POLICY "Admins update policy"
    ON public.admins FOR UPDATE
    USING (true)
    WITH CHECK (true);

